# DevOps_Prep.ps1 - the one tool for the DevOps interview prep page.
# Launched by DevOps_Prep.bat. Option 1 runs the whole chain:
#   All_questions.txt -> Excel workbook (Claude Code) -> index.html (Python)
#   -> verify -> optional commit + push to GitHub Pages.
# Every other option runs one step on its own.

Set-Location -Path $PSScriptRoot
try {
    [Console]::OutputEncoding = [System.Text.Encoding]::UTF8
    $OutputEncoding = [System.Text.Encoding]::UTF8
} catch {}

$repoRoot      = Split-Path $PSScriptRoot -Parent
$questionsFile = Join-Path $PSScriptRoot "All_questions.txt"
$historyFile   = Join-Path $PSScriptRoot ".sync_history.csv"
$excelBkpDir   = Join-Path $PSScriptRoot "bkp\excel"
$siteUrl       = "https://dikshaingole.github.io/Devops/"

function Write-Title($text) {
    Write-Host ""
    Write-Host "============================================"
    Write-Host " $text"
    Write-Host "============================================"
}

function Get-QuestionLineCount {
    if (-not (Test-Path $questionsFile)) { return 0 }
    return @(Get-Content $questionsFile -Encoding UTF8 | Where-Object { $_.Trim() -ne "" }).Count
}

function Test-WorkbookLocked {
    # Excel keeps a ~$name.xlsx lock file next to a workbook it has open.
    return [bool](Get-ChildItem -Path $PSScriptRoot -Filter '~$*.xlsx' -Force -ErrorAction SilentlyContinue)
}

# Runs a Python script with output going straight to the console (so its
# Y/N prompts stay visible) and records success in $script:PyOk. Functions
# here report status through script variables instead of return values,
# because capturing a function's return value would also capture - and
# hide - everything the programs inside it print.
function Invoke-Py([string[]]$pyArgs) {
    & python @pyArgs
    $script:PyOk = ($LASTEXITCODE -eq 0)
}

function Open-InVSCode {
    if (Get-Command code -ErrorAction SilentlyContinue) {
        code .
        Write-Host "VS Code is opening. Tell Claude Code there:"
        Write-Host '  "Follow the instructions in question_sync_prompt.md on All_questions.txt."'
    } else {
        Write-Host "VS Code ('code') was not found. Open this folder manually: $PSScriptRoot"
    }
}

# ---------- Step 1: All_questions.txt -> Excel (Claude Code) ----------
# Sets $script:StepOk to $true when the step succeeded or had nothing to do.
function Sync-QuestionsToExcel {
    $script:StepOk = $false
    Write-Title "Step 1: New questions -> Excel"
    $lineCount = Get-QuestionLineCount
    if ($lineCount -eq 0) {
        Write-Host "All_questions.txt is empty - nothing to add. Skipping."
        $script:StepOk = $true; return
    }
    if (-not (Get-Command claude -ErrorAction SilentlyContinue)) {
        Write-Host "Claude Code CLI ('claude') was not found on this machine."
        Open-InVSCode
        return
    }
    if (Test-WorkbookLocked) {
        Write-Host "The workbook is open in Excel. Close it (save first), then run this again."
        return
    }

    Write-Host "Where are these questions from?"
    Write-Host "  [1] LinkedIn post"
    Write-Host "  [2] A real interview"
    Write-Host "  [3] Something else (type your own short label)"
    switch (Read-Host "Enter 1, 2 or 3") {
        "2" { $sourceTag = "Interview" }
        "3" {
            $sourceTag = (Read-Host "Short label (e.g. Glassdoor, Naukri, MockInterview)") -replace '[^a-zA-Z0-9]', ''
            if ([string]::IsNullOrWhiteSpace($sourceTag)) { $sourceTag = "LinkedIn" }
        }
        default { $sourceTag = "LinkedIn" }
    }
    Write-Host "Using source tag: $sourceTag-1, $sourceTag-2, ..."

    Write-Host ""
    Write-Host "Non-blank lines in All_questions.txt: $lineCount"
    if (Test-Path $historyFile) {
        $past = @(Import-Csv $historyFile | ForEach-Object { [int]$_.DurationSeconds })
        if ($past.Count -gt 0) {
            $avg = [math]::Round(($past | Measure-Object -Average).Average)
            Write-Host "Past $($past.Count) run(s) took about $([math]::Floor($avg / 60))m $($avg % 60)s on average."
        }
    } else {
        Write-Host "First run here - usually a few minutes, since every question is checked against the whole workbook."
    }

    $prompt = "Follow the instructions in question_sync_prompt.md on All_questions.txt. " +
              "For this run, use '$sourceTag' as the source tag instead of the default 'LinkedIn' " +
              "(so Priority Count tags look like $sourceTag-1, $sourceTag-2, etc.). " +
              "Only edit the .xlsx workbook, All_questions.txt and files under bkp/excel/ - do not touch index.html, " +
              "scripts/ or anything outside this folder; the website is regenerated by a separate step afterwards. " +
              "IMPORTANT: this output goes to a plain Windows terminal with no Markdown rendering - " +
              "do NOT use Markdown tables (no '|' pipes, no '---' rows). Report the summary as plain indented text, " +
              "one line per question like 'Kubernetes, row 10: What is a Pod? -> LinkedIn-1 to LinkedIn-2 (Updated)', " +
              "grouped under short headings."

    $start = Get-Date
    Write-Host ""
    Write-Host "Starting Claude Code at $($start.ToString('HH:mm:ss')) - live progress below."
    Write-Host ""
    $ok = $true
    try {
        claude -p $prompt --permission-mode bypassPermissions --verbose
        if ($LASTEXITCODE -ne 0) { $ok = $false }
    } catch {
        Write-Host "Claude Code failed to run: $($_.Exception.Message)"
        $ok = $false
    }
    $duration = (Get-Date) - $start

    if (-not $ok) {
        Write-Host ""
        Write-Host "The question sync did not finish successfully."
        if ((Read-Host "Open this folder in VS Code to finish it there? (y/n)") -match '^[yY]') { Open-InVSCode }
        return
    }

    Write-Host ""
    Write-Host "Question sync done in $([math]::Floor($duration.TotalMinutes))m $($duration.Seconds)s."

    # Keep only the 10 newest workbook backups.
    if (Test-Path $excelBkpDir) {
        $old = @(Get-ChildItem $excelBkpDir -Filter *.xlsx -File | Sort-Object LastWriteTime -Descending | Select-Object -Skip 10)
        $old | Remove-Item -Force
        if ($old.Count -gt 0) { Write-Host "Pruned $($old.Count) old workbook backup(s) (keeping 10)." }
    }

    # Record the duration for future estimates (last 20 runs).
    $rows = @()
    if (Test-Path $historyFile) { $rows = @(Import-Csv $historyFile) }
    $rows += [pscustomobject]@{ StartTime = $start.ToString('yyyy-MM-dd HH:mm:ss'); DurationSeconds = [math]::Round($duration.TotalSeconds) }
    $rows | Select-Object -Last 20 | Export-Csv -Path $historyFile -NoTypeInformation -Encoding UTF8
    $script:StepOk = $true; return
}

# ---------- Step 2: Excel -> index.html (Python scripts) ----------
function Update-SiteFromExcel {
    $script:StepOk = $false
    Write-Title "Step 2: Excel -> website (index.html)"
    # Sheets already on the page: field-by-field resync (asks before removing rows).
    Invoke-Py @('scripts\smart_sync.py', '--quiet')
    if (-not $script:PyOk) { return }

    # Sheets that exist in Excel but aren't on the page yet: offer to add them.
    $missing = @(& python -c "import sys; sys.path.insert(0, 'scripts'); import extract_data as ed; have = {q['sheet'] for q in ed.read_current_data()}; print('\n'.join(s for s in ed.wb.sheetnames if s not in have))" | Where-Object { $_.Trim() -ne "" })
    if ($missing.Count -gt 0) {
        Write-Host ""
        Write-Host "Sheets in Excel that are not on the website yet:"
        $missing | ForEach-Object { Write-Host "  - $_" }
        if ((Read-Host "Add them now? (y/n)") -match '^[yY]') {
            Invoke-Py (@('scripts\add_sheets.py') + $missing)
            if (-not $script:PyOk) { return }
        }
    }

    Write-Host ""
    Invoke-Py @('scripts\verify_index.py', '--quiet')
    $script:StepOk = $script:PyOk
}

# ---------- Step 3: commit + push ----------
function Publish-ToGitHub {
    Write-Title "Step 3: Publish to GitHub Pages"
    $changes = @(git -C $repoRoot status --porcelain -- Devops .github)
    if ($changes.Count -eq 0) {
        Write-Host "No website changes to publish."
        return
    }
    Write-Host "Changes that will be committed (Excel files and backups are never committed):"
    $changes | ForEach-Object { Write-Host "  $_" }
    Write-Host ""
    if ((Read-Host "Commit and push these to GitHub? (y/n)") -notmatch '^[yY]') {
        Write-Host "Not pushed. Run this again (option 1 or 8) when you're ready."
        return
    }
    $msg = Read-Host "Commit message (Enter for 'Update DevOps interview questions')"
    if ([string]::IsNullOrWhiteSpace($msg)) { $msg = "Update DevOps interview questions" }

    git -C $repoRoot add -A -- Devops .github
    git -C $repoRoot commit -m $msg
    if ($LASTEXITCODE -ne 0) { Write-Host "Commit failed."; return }
    git -C $repoRoot pull --rebase
    if ($LASTEXITCODE -ne 0) {
        Write-Host "Pull/rebase hit a conflict. Resolve it in $repoRoot, run 'git rebase --continue', then push."
        return
    }
    git -C $repoRoot push
    if ($LASTEXITCODE -ne 0) { Write-Host "Push failed."; return }
    Write-Host ""
    Write-Host "Pushed. The site updates in a minute or two: $siteUrl"
}

function Invoke-Everything {
    Sync-QuestionsToExcel
    if (-not $script:StepOk) {
        Write-Host ""
        Write-Host "Stopped after step 1 - the website was not changed."
        return
    }
    Update-SiteFromExcel
    if (-not $script:StepOk) {
        Write-Host ""
        Write-Host "Stopped after step 2 - fix the error above before publishing (option 13 restores a page backup)."
        return
    }
    Publish-ToGitHub
}

# ---------- Menu ----------
while ($true) {
    Write-Title "DevOps Interview Prep"
    $n = Get-QuestionLineCount
    Write-Host "  All_questions.txt has $n non-blank line(s) waiting."
    Write-Host ""
    Write-Host "   1. DO EVERYTHING  (new questions -> Excel -> website -> verify -> ask to push)"
    Write-Host ""
    Write-Host "  -- One step at a time --"
    Write-Host "   2. New questions -> Excel only        (Claude Code)"
    Write-Host "   3. Excel -> website only               (smart sync + new sheets + verify)"
    Write-Host "   8. Publish to GitHub                   (shows changes, asks first)"
    Write-Host ""
    Write-Host "  -- Look / edit --"
    Write-Host "   4. Data summary          (which sheets are on the page, row counts)"
    Write-Host "   5. Preview locally       (local server + browser)"
    Write-Host "   6. Open Excel workbook"
    Write-Host "   7. Open All_questions.txt"
    Write-Host ""
    Write-Host "  -- Advanced --"
    Write-Host "   9. Add sheet             (pick by number)"
    Write-Host "  10. Remove sheet          (pick by number)"
    Write-Host "  11. Full resync           (re-extract every synced sheet)"
    Write-Host "  12. Verify index.html     (syntax, ids, data counts)"
    Write-Host "  13. Restore page backup   (pick from the last 5)"
    Write-Host "  14. Clear all data        (destructive, asks first)"
    Write-Host "  15. Settings              (port, row cap)"
    Write-Host ""
    Write-Host "   0. Exit"
    $choice = Read-Host "Choose"
    if ([string]::IsNullOrWhiteSpace($choice)) { continue }

    switch ($choice) {
        "1"  { Invoke-Everything }
        "2"  { Sync-QuestionsToExcel }
        "3"  { Update-SiteFromExcel }
        "4"  { Invoke-Py @('scripts\list_sheets.py') }
        "5"  { Invoke-Py @('scripts\serve.py') }
        "6"  { Get-ChildItem -Path $PSScriptRoot -Filter *.xlsx -File | Where-Object { $_.Name -notlike '~$*' } | ForEach-Object { Start-Process $_.FullName } }
        "7"  { if (-not (Test-Path $questionsFile)) { New-Item -ItemType File $questionsFile | Out-Null }; Start-Process notepad.exe $questionsFile }
        "8"  { Publish-ToGitHub }
        "9"  { Invoke-Py @('scripts\add_sheets_menu.py'); if ($script:PyOk) { Invoke-Py @('scripts\verify_index.py', '--quiet') } }
        "10" { Invoke-Py @('scripts\remove_sheet.py'); if ($script:PyOk) { Invoke-Py @('scripts\verify_index.py', '--quiet') } }
        "11" { Invoke-Py @('scripts\extract_data.py', '--quiet'); if ($script:PyOk) { Invoke-Py @('scripts\verify_index.py', '--quiet') } }
        "12" { Invoke-Py @('scripts\verify_index.py') }
        "13" { Invoke-Py @('scripts\restore_backup.py'); if ($script:PyOk) { Invoke-Py @('scripts\verify_index.py', '--quiet') } }
        "14" { Invoke-Py @('scripts\clear_data.py') }
        "15" { Invoke-Py @('scripts\edit_config.py') }
        "0"  { exit }
        default { Write-Host "Unknown option." }
    }
    Write-Host ""
    [void](Read-Host "Press Enter to return to the menu")
}
